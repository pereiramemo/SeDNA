def create_fasta_files(paths2gbk, output_dir, cds_id):
    """
    Extract CDS sequences from GenBank files and create corresponding FASTA files.

    Parameters:
        paths2gbk (list): List of paths to GenBank files.
        output_dir (str): Directory where the FASTA files will be saved.
        cds_id (str): Key used to identify CDS sequences in the GenBank file.

    Returns:
        list: A list of file paths (without extensions) corresponding to each processed GenBank file.
    
    Note:
        If no GenBank files are found (i.e., paths2gbk is empty), the function prints a message,
        removes the output directory, and exits the program.
    """
    if len(paths2gbk) == 0:
        print("No gbk file found")
        shutil.rmtree(output_dir)
        sys.exit(0)

    path2names = []
    for gbk in paths2gbk:
        # Get the base file name without extension
        file_name = os.path.basename(os.path.splitext(gbk)[0])
        # Construct the file path and FASTA file name
        file_path = os.path.join(output_dir, file_name)
        fasta = os.path.join(output_dir, f'{file_name}.fasta')
        path2names.append(file_path)
        # Extract the CDS sequences and write to the FASTA file
        utilities.extract_cds(input_gbk=gbk, cds_id=cds_id, output_fasta=fasta)
    
    return path2names


def run_hmm_annotation(path2names, hmms_db, evalue_thres, threads, cut_ga):
    """
    Annotate CDS sequences using hmmsearch from pyhmmer.

    Parameters:
        path2names (list): A list of base file paths (without extension) corresponding to each CDS fasta file.
        hmms_db (str): Path to the HMMs database.
        evalue_thres (float): E-value threshold to use in hmmsearch.
        threads (int): Number of threads to use in hmmsearch.
        cut_ga (bool): If True, use gathering bit score cutoffs; otherwise, do not.

    Returns:
        None

    The function creates domain table output files for each fasta file generated by hmmsearch.
    """
    for file in path2names:
        # Define input/output file paths
        fasta = f'{file}.fasta'
        domtblout = f'{file}.domtblout'

        if not cut_ga:
            with pyhmmer.plan7.HMMFile(hmms_db) as hmms:
                with pyhmmer.easel.SequenceFile(fasta, digital=True) as seqs:
                    with open(domtblout, "wb") as output_file:
                        for hits in pyhmmer.hmmer.hmmsearch(hmms, seqs, domE=evalue_thres, cpus=threads):
                            hits.write(output_file, format="domains", header=False)
        else:
            with pyhmmer.plan7.HMMFile(hmms_db) as hmms:
                with pyhmmer.easel.SequenceFile(fasta, digital=True) as seqs:
                    with open(domtblout, "wb") as output_file:
                        for hits in pyhmmer.hmmer.hmmsearch(
                            hmms, seqs, domE=evalue_thres, bit_cutoffs="gathering", cpus=threads
                        ):
                            hits.write(output_file, format="domains", header=False)
                            
def resolve_domain_structure(path2names):
    """
    Resolve domain structure for each file using cath-resolve-hits.

    This function constructs the necessary file names for each base file path in 'path2names'
    and runs the 'cath-resolve-hits' command. The command is defined as a list, and output
    redirection is handled by passing a file handle to the subprocess.

    Parameters:
        path2names (list): List of base file paths (without extensions) for each sample.
    
    Returns:
        None

    If the cath-resolve-hits command fails for any file (i.e. returns a non-zero exit code),
    an error message is printed and the program exits.
    """
    for file in path2names:
        domtblout = f'{file}.domtblout'
        output_resolved_tsv = f'{file}_annotdoms_resolved.tsv'
        
        # Build the command as a list
        command = [
            "cath-resolve-hits",
            "--input-format", "hmmer_domtblout",
            domtblout
        ]
        
        # Open the output file and run the command, redirecting stdout to the file
        with open(output_resolved_tsv, "w") as outfile:
            result = subprocess.run(
                command,
                stdout=outfile,
                stderr=subprocess.PIPE,
                text=True
            )
        
        if result.returncode != 0:
            print("Error executing cath-resolve-hits")
            print("Error message:\n", result.stderr)
            sys.exit(1)
                            
